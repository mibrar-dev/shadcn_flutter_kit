/// Wraps [child] in an [OverlayManagerLayer] unless one is already present.
///
/// Install this (or [OverlayManagerLayer]) once at the app root so every
/// overlay shares a single stack.
class ShadcnLayer extends StatelessWidget {
  /// The app subtree.
  final Widget child;

  /// Optional shadcn theme data installed above [child].
  final ShadcnThemeData? theme;

  /// Handler for popover overlays.
  final OverlayHandler popoverHandler;

  /// Handler for tooltip overlays.
  final OverlayHandler tooltipHandler;

  /// Handler for menu overlays.
  final OverlayHandler menuHandler;

  /// Creates a layer.
  const ShadcnLayer({
    super.key,
    required this.child,
    this.theme,
    this.popoverHandler = OverlayHandler.popover,
    this.tooltipHandler = OverlayHandler.popover,
    this.menuHandler = OverlayHandler.popover,
  });

  @override
  Widget build(BuildContext context) {
    Widget wrapped = child;
    if (theme != null) {
      wrapped = ShadcnTheme(data: theme!, child: wrapped);
    }
    final hasManager = Data.maybeOf<OverlayManager>(context);
    if (hasManager != null) {
      return wrapped;
    }
    return OverlayManagerLayer(
      popoverHandler: popoverHandler,
      tooltipHandler: tooltipHandler,
      menuHandler: menuHandler,
      child: wrapped,
    );
  }
}
